#!/usr/bin/env python3
"""Convert Xolotl's published V4.1 expert ranking to Gufo's built-in table.

The ranking is a cache-placement hint from a different quant, not model
weights. The complete source file is pinned by SHA-256; preserve its source
attribution and license when changing the generated table.
"""

import argparse
import hashlib
from pathlib import Path
import struct

SOURCE_SHA256 = "5e49d8db7e581f13d81a0dc7737046bc893016872f3a2e85b8fa84b46d72c39f"
EXPERTS = 40 * 384


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Xolotl rank-1017-v4.bin")
    parser.add_argument("output", type=Path, help="Generated C++ include")
    args = parser.parse_args()
    data = args.source.read_bytes()
    if hashlib.sha256(data).hexdigest() != SOURCE_SHA256:
        parser.error("source file does not match the pinned ranking")
    ranks = list(struct.iter_unpack("<ii", data))
    if len(ranks) != EXPERTS or len(set(ranks)) != EXPERTS or any(
        not (0 <= layer < 40 and 0 <= expert < 384) for layer, expert in ranks
    ):
        parser.error("ranking is not a permutation of the 40 x 384 experts")
    values = [layer * 384 + expert for layer, expert in ranks]
    with args.output.open("w", encoding="ascii") as out:
        out.write("/* Generated by tools/ds41/import_expert_rank.py; see licenses/xolotl-expert-rank.txt. */\n")
        for at in range(0, len(values), 16):
            out.write("  " + ", ".join(map(str, values[at:at + 16])) + ",\n")


if __name__ == "__main__":
    main()
