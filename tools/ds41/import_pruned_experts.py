#!/usr/bin/env python3
"""Convert an expert-pruned release's kept-experts list to a built-in Gufo table.

Expert-pruned builds keep a subset of the 384 routed experts per layer and
renumber them. The streamed expert store maps the built-in V4.1 ranking
through this table to seed its cache. The GGUF does not carry the mapping, so
the store recognizes the build by a fingerprint of its routing biases
(FNV-1a 64 over every layer's `exp_probs_b.bias` bytes, in layer order).

The source file is pinned by SHA-256; keep its attribution and license
(licenses/) when changing the generated table.
"""

import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from gufo.gguf import parse_gguf  # noqa: E402

N_LAYER = 40
MAX_EXPERT = 384
BUILDS = {
    # ISTA-DASLab DeepSeek-V4.1-Flash-1017-GSQ-RCO-Coder-GGUF, IQ2_XXS
    "e2f58383921b42390836f5d335dfcd5a18f31e4eec9c2335253e99fb9116003a": "kGsqRcoCoder",
}


def bias_fingerprint(first_shard: Path) -> int:
    match = re.fullmatch(r"(.*)-00001-of-(\d{5})\.gguf", str(first_shard))
    if not match:
        raise SystemExit("expected the first GGUF shard, ending -00001-of-NNNNN.gguf")
    biases = {}
    for i in range(1, int(match[2]) + 1):
        path = Path(f"{match[1]}-{i:05d}-of-{match[2]}.gguf")
        gguf = parse_gguf(path)
        with path.open("rb") as f:
            for tensor in gguf["tensors"]:
                name = re.fullmatch(r"blk\.(\d+)\.exp_probs_b\.bias", tensor["name"])
                if name:
                    f.seek(gguf["data_offset"] + tensor["offset"])
                    biases[int(name[1])] = f.read(4 * tensor["shape"][-1])
    if sorted(biases) != list(range(N_LAYER)):
        raise SystemExit("every layer needs exp_probs_b.bias")
    h = 0xCBF29CE484222325
    for layer in range(N_LAYER):
        for byte in biases[layer]:
            h = ((h ^ byte) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("kept", type=Path, help="the release's *.kept-experts.json")
    parser.add_argument("model", type=Path, help="first GGUF shard of the same build")
    parser.add_argument("output", type=Path, help="generated C++ include")
    args = parser.parse_args()
    data = args.kept.read_bytes()
    name = BUILDS.get(hashlib.sha256(data).hexdigest())
    if not name:
        parser.error("kept-experts file does not match a pinned release")
    kept = json.loads(data)
    rows = [kept["kept_experts"][str(layer)] for layer in range(N_LAYER)]
    n = len(rows[0])
    if kept["layers"] != N_LAYER or kept["experts_per_layer"] != MAX_EXPERT or kept["kept_per_layer"] != n or any(
        len(row) != n or row != sorted(set(row)) or not all(0 <= e < MAX_EXPERT for e in row) for row in rows
    ):
        parser.error("kept experts are not increasing, distinct original ids with one count per layer")
    fingerprint = bias_fingerprint(args.model)
    with args.output.open("w", encoding="ascii") as out:
        out.write("/* Generated by tools/ds41/import_pruned_experts.py; see licenses/ista-daslab-kept-experts.txt. */\n")
        out.write(f"inline constexpr PrunedBuild {name} = {{\n    0x{fingerprint:016x}ull,\n    {n},\n    {{\n")
        for row in rows:
            for at in range(0, n, 16):
                out.write("        " + ", ".join(map(str, row[at:at + 16])) + ",\n")
        out.write("    }};\n")


if __name__ == "__main__":
    main()
